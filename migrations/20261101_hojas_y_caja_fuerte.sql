-- 2026-11-01 — Hojas tipo Excel y Caja fuerte.
-- Solo agrega: no cambia ni borra ningún recordatorio. Los existentes quedan con aviso y
-- rojo encendidos, que es como ya funcionaban.
-- Ya aplicada en produccion via MCP.

-- Hojas. tipo: recordatorios (guarda las columnas extra de la hoja fija; una por usuario),
-- normal (creada por el usuario) o caja (una por usuario; sus filas van en caja_filas).
CREATE TABLE IF NOT EXISTS public.hojas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  nombre text NOT NULL,
  tipo text NOT NULL DEFAULT 'normal' CHECK (tipo IN ('recordatorios', 'normal', 'caja')),
  columnas jsonb NOT NULL DEFAULT '[]'::jsonb,
  orden integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS hojas_user_idx ON public.hojas (user_id);
CREATE UNIQUE INDEX IF NOT EXISTS hojas_unica_por_tipo
  ON public.hojas (user_id, tipo) WHERE tipo <> 'normal';

ALTER TABLE public.reminders
  ADD COLUMN IF NOT EXISTS color text,
  ADD COLUMN IF NOT EXISTS prioridad text NOT NULL DEFAULT 'baja',
  ADD COLUMN IF NOT EXISTS avisar boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS rojo boolean NOT NULL DEFAULT true,
  ADD COLUMN IF NOT EXISTS extras jsonb NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN IF NOT EXISTS hoja_id bigint REFERENCES public.hojas(id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS reminders_hoja_idx ON public.reminders (hoja_id) WHERE hoja_id IS NOT NULL;

-- Caja fuerte: cada fila es un solo texto cifrado en el celular con AES-256-GCM. La base
-- no guarda nombres, usuarios, claves ni notas legibles.
CREATE TABLE IF NOT EXISTS public.caja_filas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  cifrado text NOT NULL CHECK (length(cifrado) <= 20000),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS caja_filas_user_idx ON public.caja_filas (user_id);

-- Llave de cada caja, cifrada con CAJA_SECRETO (variable de Vercel), y hash del PIN.
-- Solo la toca /api/caja con la service key: sin permisos ni políticas para los usuarios.
CREATE TABLE IF NOT EXISTS public.caja_llaves (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  llave_cifrada text NOT NULL,
  pin_hash text NOT NULL,
  pin_sal text NOT NULL,
  intentos integer NOT NULL DEFAULT 0,
  bloqueos integer NOT NULL DEFAULT 0,
  bloqueada_hasta timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.hojas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.caja_filas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.caja_llaves ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS hojas_user_policy ON public.hojas;
CREATE POLICY hojas_user_policy ON public.hojas FOR ALL TO authenticated
  USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS caja_filas_user_policy ON public.caja_filas;
CREATE POLICY caja_filas_user_policy ON public.caja_filas FOR ALL TO authenticated
  USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

REVOKE ALL ON public.hojas, public.caja_filas, public.caja_llaves FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.hojas, public.caja_filas TO authenticated;
GRANT ALL ON public.hojas, public.caja_filas, public.caja_llaves TO service_role;
